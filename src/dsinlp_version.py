        self.cross_refs = {}
        total_refs = 0
        for key, entrada in self.glossario.items():
            defn = (entrada.definicao or "").lower()
            tokens = set(re.findall(r"\b[a-záéíóúâêôãõçü]{4,}\b", defn))
            refs = tokens & termos_base
            for tc in termos_compostos:
                if tc != entrada.termo_normalizado and tc in defn:
                    refs.add(tc)
