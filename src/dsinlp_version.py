    def _categorizar_por_refs(self, termo, definicao, refs, anchors_map):
        """Categoriza um termo via 3 hops:
        Hop 0: o termo É uma âncora
        Hop 1: a definição menciona uma âncora
        Hop 2: a definição menciona um termo cuja definição menciona uma âncora
        """
        defn = (definicao or "").lower()

        # Hop 0
        for cat, anchors in anchors_map.items():
            for a in anchors:
                if a == termo:
                    return cat, "direto_hop0"

        # Hop 1: âncora aparece na definição
        scores = Counter()
        for cat, anchors in anchors_map.items():
            for a in anchors:
                if re.search(r"\b" + re.escape(a) + r"\b", defn):
                    scores[cat] += 1
        if scores:
            return scores.most_common(1)[0][0], "direto_hop1"

        # Hop 2: via cross-refs
        for ref in refs:
            ref_defn = ""
            for k, e in self.glossario.items():
                if e.termo_normalizado == ref:
                    ref_defn = (e.definicao or "").lower()
                    break
            for cat, anchors in anchors_map.items():
                for a in anchors:
                    if re.search(r"\b" + re.escape(a) + r"\b", ref_defn):
                        scores[cat] += 1
        if scores:
            return scores.most_common(1)[0][0], "cross_ref_1hop"

        return "desconhecido", "sem_match"

    def _categorizar_sub_anchor(self, termo, definicao, sub_anchors):
        """Categoriza via sub-âncoras do capítulo. Busca palavras-chave no termo + definição."""
        text = (termo + " " + (definicao or "")).lower()
        scores = Counter()
        for subcat, keywords in sub_anchors.items():
            for kw in keywords:
                if re.search(r"\b" + re.escape(kw.lower()) + r"\b", text):
                    scores[subcat] += 1
        if scores:
            return scores.most_common(1)[0][0]
        return "desconhecido"

