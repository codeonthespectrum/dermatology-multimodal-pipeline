@dataclass
class EntradaGlossarioV2:
    termo: str
    termo_normalizado: str
    definicao: str
    capitulo: str = "?"
    pagina: int = -1
    patofisiologia: str = "desconhecido"
    morfologia: str = "desconhecido"
    categoria_cientifica: str = "desconhecido"
    keywords_encontradas: List[str] = field(default_factory=list)

_CHAPTERS_MAP = {
    "I":   "Cap I — Semiologia",
    "II":  "Cap II — Cabelo (Tricopatologia)",
    "III": "Cap III — Unhas (Onicopatologia)",
    "IV":  "Cap IV — Mucosas",
    "V":   "Cap V — Dermatoscopia",
    "VI":  "Cap VI — Histologia da pele",
    "VII": "Cap VII — Dermatoses",
}
_SKIP_FIRST_N_PAGES = 20
_RE_CHAPTER = re.compile(r"apítulo\s+([IVX]+)", re.IGNORECASE)

def _is_term_span(s):
    return "Heavy" in s["font"] and abs(round(s["size"], 1) - 12.0) < 0.5
def _is_chapter_span(s):
    return "LightCondense" in s["font"] and abs(round(s["size"], 1) - 21.0) < 1.0
def _is_body_span(s):
    return "MyriadPro" in s["font"] and round(s["size"], 1) <= 11
def _is_figure_caption_span(s):
    f, sz = s["font"], round(s["size"], 1)
    return (("Bold" in f or "Italic" in f) and "Heavy" not in f
            and "BoldCondensed" not in f and 8.5 <= sz <= 9.5)

def _classify_line(spans):
    if any(_is_chapter_span(s) for s in spans):        return "chapter"
    if any(_is_term_span(s) for s in spans):            return "term"
    if any(_is_figure_caption_span(s) for s in spans):  return "figure"
    if any(_is_body_span(s) for s in spans):            return "body"
    return "ignore"

def _post_process_def(text):
    text = re.sub(r"(\w)-\s+(\w)", r"\1\2", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def parse_glossario_v2(pdf_path: str) -> Dict[str, EntradaGlossarioV2]:
    print("\n" + "=" * 60)
    print("📖 PARSER v2 — Glossário com estrutura nativa")
    print("=" * 60)

    if not os.path.exists(pdf_path):
        print(f"   ❌ Não encontrado: {pdf_path}")
        return {}

    doc = fitz.open(pdf_path)
    print(f"   PDF: {len(doc)} páginas (pulando primeiras {_SKIP_FIRST_N_PAGES})")

    entries = []
    state, term_parts, def_lines = "WAITING", [], []
    cur_chap, cur_page = "?", -1
    current_chapter = "?"
    chapter_log = []

    def finalize():
        nonlocal term_parts, def_lines
        if not term_parts:
            return
        term = re.sub(r"\s+", " ", " ".join(term_parts)).strip().rstrip(":,;. ")
        if not term or term.isdigit() or len(term) < 2:
            term_parts, def_lines = [], []
            return
        if def_lines:
            definicao = _post_process_def(" ".join(def_lines))
            if len(definicao) >= 20:
                entries.append({
                    "termo": term,
                    "termo_normalizado": term.lower().strip(),
                    "definicao": definicao,
                    "capitulo": cur_chap,
                    "pagina": cur_page,
                })
        term_parts, def_lines = [], []

    for page_idx in range(_SKIP_FIRST_N_PAGES, len(doc)):
        for block in doc[page_idx].get_text("dict")["blocks"]:
            if block.get("type") != 0:
                continue
            for line in block.get("lines", []):
                spans = line["spans"]
                line_text = "".join(s["text"] for s in spans).strip()
                if not line_text:
                    continue
                kind = _classify_line(spans)
                if kind == "chapter":
                    m = _RE_CHAPTER.search(line_text)
                    if m:
                        roman = m.group(1).upper()
                        if roman in _CHAPTERS_MAP:
                            current_chapter = _CHAPTERS_MAP[roman]
                            chapter_log.append((page_idx + 1, current_chapter))
                    continue
                if kind == "term":
                    term_text = re.sub(r"\s+", " ",
                        "".join(s["text"] for s in spans if _is_term_span(s))).strip()
                    if not term_text or term_text.isdigit():
                        continue
                    if state == "COLLECTING_TERM":
                        term_parts.append(term_text)
                    else:
                        if state == "COLLECTING_DEF":
                            finalize()
                        term_parts = [term_text]; def_lines = []
                        cur_chap = current_chapter; cur_page = page_idx + 1
                        state = "COLLECTING_TERM"
                    continue
                if kind == "body":
                    if state == "COLLECTING_TERM":
                        state = "COLLECTING_DEF"
                        def_lines.append(line_text)
                    elif state == "COLLECTING_DEF":
                        def_lines.append(line_text)
                    continue
    finalize()
    doc.close()

    print(f"\n   Capítulos detectados ({len(chapter_log)}):")
    for p, c in chapter_log:
        print(f"      p{p:>4}: {c}")

    glossario: Dict[str, EntradaGlossarioV2] = {}
    duplicatas = 0
    for d in entries:
        key = d["termo_normalizado"]
        if key in glossario:
            duplicatas += 1
            cap_short = d["capitulo"].split("—")[0].strip().replace(" ", "_").lower()
            key = f"{d['termo_normalizado']} [{cap_short}]"
        glossario[key] = EntradaGlossarioV2(
            termo=d["termo"],
            termo_normalizado=d["termo_normalizado"],
            definicao=d["definicao"],
            capitulo=d["capitulo"],
            pagina=d["pagina"],
        )

    print(f"\n   Total: {len(glossario)} termos | {duplicatas} duplicatas inter-cap")
    print(f"\n   Distribuição por capítulo:")
    for chap, n in Counter(e.capitulo for e in glossario.values()).most_common():
        bar = "█" * int(n / 5)
        print(f"      {chap:<50} {n:>4}  {bar}")
    return glossario


