class ClinicalVariableProcessor:
    def __init__(self):
        self.idades = []
        self.loc_map = {}
        self.loc_counter = 0

    def coletar(self, idade, sexo, loc):
        # Idade
        idade_val = None
        try:
            idade_val = float(idade)
            if not (0 < idade_val < 120):
                idade_val = None
            else:
                self.idades.append(idade_val)
        except (ValueError, TypeError):
            pass

        # Sexo
        sexo_str = "unknown"
        if sexo:
            s = str(sexo).lower().strip()
            if s in ("male", "m", "masculino"):
                sexo_str = "male"
            elif s in ("female", "f", "feminino"):
                sexo_str = "female"

        # Localização
        loc_str = "unknown"
        if loc:
            loc_str = str(loc).lower().strip()
            if loc_str and loc_str not in self.loc_map:
                self.loc_map[loc_str] = self.loc_counter
                self.loc_counter += 1

        return {"idade": idade_val, "sexo": sexo_str, "localizacao": loc_str}

