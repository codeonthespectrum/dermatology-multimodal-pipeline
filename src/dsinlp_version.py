        plt.show()

        pairs = []
        for i in range(n_cats):
            for j in range(i + 1, n_cats):
                if not np.isnan(jacc[i, j]) and jacc[i, j] > 0:
                    pairs.append((cats_unique[i], cats_unique[j], jacc[i, j]))
        pairs.sort(key=lambda x: -x[2])
        print(f"\n  Categorias × Categorias com maior Jaccard (top 10):")
        for a, b, j in pairs[:10]:
            print(f"    {a[:35]:35s} ↔ {b[:35]:35s} J={j:.3f}")
