        print("\n  Recalculando TF-IDF (não estava na DB)…")
        secoes_df = pd.read_sql("SELECT id, LOWER(texto) as texto FROM secoes_azulay", conn)
        termos_df = pd.read_sql(
            "SELECT termo_normalizado, frequencia, patofisiologia, categoria_cientifica "
            "FROM termos_dsinlp WHERE frequencia > 0", conn)
        N = max(len(secoes_df), 1)
        textos = secoes_df["texto"].tolist()

        def doc_freq(termo):
            patt = re.compile(r"\b" + re.escape(termo) + r"\b")
            return sum(1 for tx in textos if patt.search(tx))

        termos_df["df"] = termos_df["termo_normalizado"].apply(doc_freq)
        termos_df["idf"] = np.log((N + 1) / (termos_df["df"] + 1)) + 1
        termos_df["tfidf"] = termos_df["frequencia"] * termos_df["idf"]

        # Scatter
        fig, ax = plt.subplots(figsize=(13, 7))
        for pato in termos_df["patofisiologia"].unique():
            sub = termos_df[termos_df["patofisiologia"] == pato]
            ax.scatter(sub["frequencia"], sub["tfidf"],
                       color=COLORS_PATO.get(pato, "#999"),
                       alpha=0.55, s=28, edgecolor="white", linewidth=0.4,
                       label=pato)
        top15 = termos_df.nlargest(15, "tfidf")
        for _, r in top15.iterrows():
            ax.annotate(r["termo_normalizado"],
                        xy=(r["frequencia"], r["tfidf"]),
                        xytext=(4, 3), textcoords="offset points", fontsize=8)
