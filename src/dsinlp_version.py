        for _, r in termos_df.nlargest(10, "tfidf").iterrows():
            print(f"    {r['termo_normalizado']:30s} tfidf={r['tfidf']:8.1f}  "
                  f"freq={int(r['frequencia']):>4}  df={int(r['df']):>3}  "
                  f"pato={r['patofisiologia']}")

        # ── D2: Jaccard de categorias nas seções (tabela features_binarias)
        feat = pd.read_sql(
            "SELECT secao_id, categoria FROM features_binarias WHERE valor=1", conn)
        conn.close()

        sec_cats = feat.groupby("secao_id")["categoria"].apply(set).to_dict()
        cats_unique = sorted(feat["categoria"].unique())
        idx = {c: i for i, c in enumerate(cats_unique)}
        n_cats = len(cats_unique)
        cooc = np.zeros((n_cats, n_cats))
        for _, cats in sec_cats.items():
            for c1 in cats:
                for c2 in cats:
                    cooc[idx[c1], idx[c2]] += 1
        diag = np.diag(cooc).copy()
        with np.errstate(divide="ignore", invalid="ignore"):
            jacc = cooc / (diag[:, None] + diag[None, :] - cooc)
            jacc = np.nan_to_num(jacc)
        np.fill_diagonal(jacc, np.nan)

        fig, ax = plt.subplots(figsize=(13, 11))
        im = ax.imshow(jacc, cmap="viridis", aspect="auto", vmin=0, vmax=1)
        ax.set_xticks(range(n_cats))
