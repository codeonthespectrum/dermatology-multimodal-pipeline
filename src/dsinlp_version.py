def _normalizar_dx(dx_text: str, normalizacao: dict) -> str:
    """Aplica regras de normalização (maiores primeiro pra capturar compostos)."""
    t = dx_text.lower()
    for k in sorted(normalizacao, key=len, reverse=True):
        v = normalizacao[k]
        t = re.sub(r"\b" + re.escape(k) + r"\b", v, t)
    return t


def _term_variants(t: str) -> Set[str]:
    """Gera variantes de um termo do glossário pra matching robusto:
       1) original
       2) sem parênteses (ex: 'nevo displásico (nevo de clark)' → 'nevo displásico')
       3) só até a primeira vírgula (ex: 'lentigo maligno, melanoma do lentigo' → 'lentigo maligno')
    """
    v = {t}
    t1 = re.sub(r"\([^)]*\)", " ", t)
    t1 = re.sub(r"\s+", " ", t1).strip().rstrip(",.;:")
    if t1 and t1 != t and len(t1) >= 4:
        v.add(t1)
    t2 = re.sub(r",\s*.*$", "", t).strip()
    if t2 and t2 != t and len(t2) >= 4:
        v.add(t2)
    return v


def _build_glossario_extended(glossario_termos_base: Set[str],
                               normalizacao: dict) -> Dict[str, Set[str]]:
    """Pré-calcula índice de matching robusto.
    Retorna: variante_canonica → set(termo_original_do_glossário)

    Cada termo do glossário contribui múltiplas chaves:
      - variantes do termo original (sem parênteses, sem sufixo virgular)
      - variantes do termo APÓS normalização inter-língua (queratose→ceratose, etc.)

    Isso garante que se o glossário tem 'queratose seborreica' e o dx normalizado
    é 'ceratose seborreica', ainda assim o match acontece.
    """
    extended: Dict[str, Set[str]] = {}
    for tn in glossario_termos_base:
        for v in _term_variants(tn):
            extended.setdefault(v, set()).add(tn)
        tn_norm = _normalizar_dx(tn, normalizacao)
        if tn_norm != tn:
            for v in _term_variants(tn_norm):
                extended.setdefault(v, set()).add(tn)
    return extended


def encontrar_termos_glossario_para_imagem(dx_original: str,
                                            dataset: str,
                                            engine,
                                            glossario_extended,
                                            base_to_keys):
    """Versão v3: robusta a parênteses, modificadores, variantes inter-língua.

    Retorna {'seed': [...], '1hop': [...]}.
    """
    seed_terms: Set[str] = set()

    if dataset == "ham10000":
        for cand in _HAM_SEEDS.get(dx_original.lower(), []):
            cn = cand.lower()
            if cn in glossario_extended:
                seed_terms.update(glossario_extended[cn])

    else:  # derm7pt
        # 1. Limpeza: remove parênteses do dx ("melanoma (in situ)" → "melanoma")
        dx_clean = re.sub(r"\([^)]*\)", " ", dx_original.lower())
        dx_clean = re.sub(r"\s+", " ", dx_clean).strip()

        # 2. Normalização (regras compostas primeiro)
        dx_norm = _normalizar_dx(dx_clean, engine.normalizacao)

        # 3. Match exato contra qualquer das 3 formas
        for cand in [dx_original.lower(), dx_clean, dx_norm]:
            if cand in glossario_extended:
                seed_terms.update(glossario_extended[cand])

        # 4. Substring BIDIRECIONAL contra variantes do glossário
        for variante, originais in glossario_extended.items():
            if len(variante) < 5:
                continue
            # variante do glossário cabe no dx (ex: "melanoma" cabe em "melanoma (less than ...)")
            if variante in dx_norm or variante in dx_clean:
                seed_terms.update(originais)
            # OU o dx cabe na variante (ex: "lentigo" cabe em "lentigo maligno extrafacial")
            elif ((len(dx_norm) >= 5 and dx_norm in variante) or
                  (len(dx_clean) >= 5 and dx_clean in variante)):
                seed_terms.update(originais)

    # Expansão 1-hop via cross-refs
    expansion: Set[str] = set()
    for seed in seed_terms:
        for key in base_to_keys.get(seed, []):
            expansion.update(engine.cross_refs.get(key, set()))
    expansion -= seed_terms

    return {"seed": sorted(seed_terms), "1hop": sorted(expansion)}


