def enriquecer_banco(db_path, engine, imgs_ham, imgs_d7):
    print("\n" + "=" * 60)
    print("💾 ENRIQUECIMENTO DO BANCO")
    print("=" * 60)

    import sqlite3
    conn = sqlite3.connect(db_path)
    c = conn.cursor()

    c.execute("PRAGMA table_info(glossario)")
    cols = [r[1] for r in c.fetchall()]
    if "capitulo" not in cols:
        c.execute("ALTER TABLE glossario ADD COLUMN capitulo TEXT")
    if "pagina" not in cols:
        c.execute("ALTER TABLE glossario ADD COLUMN pagina INTEGER")

    n_upd = 0
    for key, e in engine.glossario.items():
        c.execute("UPDATE glossario SET capitulo=?, pagina=? WHERE termo_normalizado=?",
                  (e.capitulo, e.pagina, e.termo_normalizado))
        n_upd += c.rowcount
    print(f"   Tabela `glossario`: capitulo/pagina populados em {n_upd} linhas")

    c.execute("PRAGMA table_info(termos_dsinlp)")
    cols = [r[1] for r in c.fetchall()]
    if "capitulo" not in cols:
        c.execute("ALTER TABLE termos_dsinlp ADD COLUMN capitulo TEXT")
    if "pagina" not in cols:
        c.execute("ALTER TABLE termos_dsinlp ADD COLUMN pagina INTEGER")

    tn_map = {}
    for e in engine.glossario.values():
        tn_map.setdefault(e.termo_normalizado, (e.capitulo, e.pagina))

    n_upd = 0
    for tn, (cap, pag) in tn_map.items():
        c.execute("UPDATE termos_dsinlp SET capitulo=?, pagina=? WHERE termo_normalizado=?",
                  (cap, pag, tn))
        n_upd += c.rowcount
    print(f"   Tabela `termos_dsinlp`: capitulo/pagina populados em {n_upd} linhas")

    c.execute("DROP TABLE IF EXISTS imagens_termos_glossario")
    c.execute("""CREATE TABLE imagens_termos_glossario (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        imagem_id TEXT NOT NULL,
        dataset TEXT NOT NULL,
        termo_normalizado TEXT NOT NULL,
        relacionamento TEXT NOT NULL
    )""")
    c.execute("CREATE INDEX idx_itg_imagem ON imagens_termos_glossario(imagem_id)")
    c.execute("CREATE INDEX idx_itg_termo ON imagens_termos_glossario(termo_normalizado)")
    c.execute("CREATE INDEX idx_itg_dataset ON imagens_termos_glossario(dataset)")

    n_ins = 0
    for img in imgs_ham:
        for t in getattr(img, "termos_seed", []):
            c.execute("INSERT INTO imagens_termos_glossario "
                      "(imagem_id, dataset, termo_normalizado, relacionamento) "
                      "VALUES (?, 'ham10000', ?, 'seed')", (img.id, t))
            n_ins += 1
        for t in getattr(img, "termos_1hop", []):
            c.execute("INSERT INTO imagens_termos_glossario "
                      "(imagem_id, dataset, termo_normalizado, relacionamento) "
                      "VALUES (?, 'ham10000', ?, '1hop')", (img.id, t))
            n_ins += 1
    for img in imgs_d7:
        for t in getattr(img, "termos_seed", []):
            c.execute("INSERT INTO imagens_termos_glossario "
                      "(imagem_id, dataset, termo_normalizado, relacionamento) "
                      "VALUES (?, 'derm7pt', ?, 'seed')", (img.id, t))
            n_ins += 1
        for t in getattr(img, "termos_1hop", []):
            c.execute("INSERT INTO imagens_termos_glossario "
                      "(imagem_id, dataset, termo_normalizado, relacionamento) "
                      "VALUES (?, 'derm7pt', ?, '1hop')", (img.id, t))
            n_ins += 1

    conn.commit()
    conn.close()
    print(f"   Tabela `imagens_termos_glossario`: {n_ins:,} relações inseridas")


